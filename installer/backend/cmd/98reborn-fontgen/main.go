// 98reborn-fontgen converts Terminus console fonts (SIL Open Font License
// 1.1, from Alpine's signed font-terminus package) into a C header for
// 98Reborn Boot and raw PSF files for the installer's graphical screens.
//
//	go run ./cmd/98reborn-fontgen --c ../boot/src/font.h --psf internal/gui/fonts
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/binary"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/win9x-modern/w9xm/internal/apk"
)

// The sizes we use: n = normal, b = bold; the number is the pixel height.
var faces = []string{"ter-116n", "ter-120n", "ter-120b", "ter-124n", "ter-124b", "ter-132b"}

type psf struct {
	name         string
	w, h, stride int
	glyphs       [][]byte // first 256
}

func parse(name string, gz []byte) (*psf, error) {
	z, err := gzip.NewReader(bytes.NewReader(gz))
	if err != nil {
		return nil, err
	}
	b, err := io.ReadAll(z)
	if err != nil {
		return nil, err
	}
	le := binary.LittleEndian
	if b[0] == 0x36 && b[1] == 0x04 { // PSF1: 8 pixels wide, height in byte 3
		f := &psf{name: name, w: 8, h: int(b[3]), stride: 1}
		for i := 0; i < 256; i++ {
			f.glyphs = append(f.glyphs, b[4+i*f.h:4+(i+1)*f.h])
		}
		return f, nil
	}
	if le.Uint32(b) != 0x864ab572 {
		return nil, fmt.Errorf("%s: not a PSF font", name)
	}
	hdr := int(le.Uint32(b[8:]))
	n := int(le.Uint32(b[16:]))
	per := int(le.Uint32(b[20:]))
	f := &psf{name: name, h: int(le.Uint32(b[24:])), w: int(le.Uint32(b[28:]))}
	f.stride = (f.w + 7) / 8
	for i := 0; i < min(n, 256); i++ {
		f.glyphs = append(f.glyphs, b[hdr+i*per:hdr+(i+1)*per])
	}
	return f, nil
}

func main() {
	cOut := flag.String("c", "", "write a C header here")
	psfDir := flag.String("psf", "", "write raw PSF2 files (first 256 glyphs) here")
	flag.Parse()
	cache, _ := os.UserCacheDir()
	c := &apk.Client{Mirror: "https://dl-cdn.alpinelinux.org/alpine", Branch: "v3.24", Arch: "x86_64", Cache: filepath.Join(cache, "98reborn", "apk")}
	for _, r := range []string{"main", "community"} {
		if err := c.LoadIndex(r); err != nil {
			panic(err)
		}
	}
	p := c.Lookup("font-terminus")
	raw, err := c.Fetch(p)
	if err != nil {
		panic(err)
	}
	files := map[string][]byte{}
	var license []byte
	apk.Unpack(raw, func(e apk.Entry) error {
		base := filepath.Base(e.Path)
		if strings.HasPrefix(e.Path, "usr/share/consolefonts/") {
			files[strings.TrimSuffix(base, ".psf.gz")] = e.Data
		}
		if strings.Contains(strings.ToLower(e.Path), "license") || strings.Contains(e.Path, "OFL") {
			license = e.Data
		}
		return nil
	})
	var fonts []*psf
	for _, name := range faces {
		f, err := parse(name, files[name])
		if err != nil {
			panic(err)
		}
		fonts = append(fonts, f)
	}
	if *cOut != "" {
		var b strings.Builder
		fmt.Fprintf(&b, "/* Generated by 98reborn-fontgen from Alpine %s %s. Do not edit.\n", p.Name, p.Version)
		b.WriteString(" *\n * Terminus Font, Copyright (C) Dimitar Toshkov Zhekov.\n")
		b.WriteString(" * Licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).\n */\n")
		b.WriteString("#pragma once\n\nstruct font { int w, h, stride; const unsigned char *bits; };\n\n")
		for _, f := range fonts {
			id := strings.ReplaceAll(f.name, "-", "_")
			fmt.Fprintf(&b, "static const unsigned char %s_bits[] = {", id)
			i := 0
			for _, g := range f.glyphs {
				for _, x := range g {
					if i%24 == 0 {
						b.WriteString("\n  ")
					}
					fmt.Fprintf(&b, "0x%02x,", x)
					i++
				}
			}
			fmt.Fprintf(&b, "\n};\nstatic const struct font %s = { %d, %d, %d, %s_bits };\n\n", id, f.w, f.h, f.stride, id)
		}
		if err := os.WriteFile(*cOut, []byte(b.String()), 0o644); err != nil {
			panic(err)
		}
		fmt.Println("wrote", *cOut)
	}
	if *psfDir != "" {
		os.MkdirAll(*psfDir, 0o755)
		for _, f := range fonts {
			// A minimal PSF2: header + 256 glyphs, no unicode table.
			var b bytes.Buffer
			per := f.stride * f.h
			for _, v := range []uint32{0x864ab572, 0, 32, 0, 256, uint32(per), uint32(f.h), uint32(f.w)} {
				binary.Write(&b, binary.LittleEndian, v)
			}
			for _, g := range f.glyphs {
				b.Write(g)
			}
			os.WriteFile(filepath.Join(*psfDir, f.name+".psf"), b.Bytes(), 0o644)
		}
		if license != nil {
			os.WriteFile(filepath.Join(*psfDir, "OFL.txt"), license, 0o644)
		}
		fmt.Println("wrote", *psfDir)
	}
}
