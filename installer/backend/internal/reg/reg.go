// Package reg renders registry changes for Windows 98.
//
// Win98's SYSTEM.DAT/USER.DAT (CREG format) can't be edited offline with NT
// tools, so we emit:
//   - a REGEDIT4 .REG file for value sets, imported by real-mode REGEDIT from
//     AUTOEXEC.BAT on the next boot (before Windows loads);
//   - a setupx INF with a DelReg section for deletions (Win98's REGEDIT4
//     importer has no delete syntax), run once at first boot via RunOnce.
package reg

import (
	"bytes"
	"encoding/hex"
	"fmt"
	"strconv"
	"strings"
)

var roots = map[string]string{
	"HKLM": "HKEY_LOCAL_MACHINE", "HKEY_LOCAL_MACHINE": "HKEY_LOCAL_MACHINE",
	"HKCU": "HKEY_CURRENT_USER", "HKEY_CURRENT_USER": "HKEY_CURRENT_USER",
	"HKCR": "HKEY_CLASSES_ROOT", "HKEY_CLASSES_ROOT": "HKEY_CLASSES_ROOT",
	"HKU": "HKEY_USERS", "HKEY_USERS": "HKEY_USERS",
	"HKCC": "HKEY_CURRENT_CONFIG", "HKEY_CURRENT_CONFIG": "HKEY_CURRENT_CONFIG",
}

var shortRoots = map[string]string{
	"HKEY_LOCAL_MACHINE": "HKLM", "HKEY_CURRENT_USER": "HKCU",
	"HKEY_CLASSES_ROOT": "HKCR", "HKEY_USERS": "HKU", "HKEY_CURRENT_CONFIG": "HKCC",
}

// SplitRoot splits "HKLM\Software\X" into ("HKEY_LOCAL_MACHINE", "Software\X").
func SplitRoot(path string) (string, string, error) {
	path = strings.Trim(strings.ReplaceAll(path, "/", `\`), `\`)
	r, rest, _ := strings.Cut(path, `\`)
	root, ok := roots[strings.ToUpper(r)]
	if !ok {
		return "", "", fmt.Errorf("registry path %q must start with HKLM, HKCU, HKCR, HKU or HKCC", path)
	}
	if rest == "" {
		return "", "", fmt.Errorf("registry path %q has no subkey", path)
	}
	return root, rest, nil
}

type Value struct {
	Root, Key, Name string // Name "" or "@" = default value
	Type            string // sz | dword | binary
	Data            string
	raw             string // rendered REGEDIT4 data
}

func NewValue(path, name, typ, data string) (Value, error) {
	root, key, err := SplitRoot(path)
	if err != nil {
		return Value{}, err
	}
	v := Value{Root: root, Key: key, Name: name, Type: typ, Data: data}
	switch typ {
	case "sz":
		v.raw = quote(data)
	case "dword":
		n, err := strconv.ParseUint(data, 0, 32)
		if err != nil {
			return Value{}, fmt.Errorf("dword data %q: %v", data, err)
		}
		v.raw = fmt.Sprintf("dword:%08x", n)
	case "binary":
		clean := strings.NewReplacer(",", "", " ", "").Replace(data)
		b, err := hex.DecodeString(clean)
		if err != nil {
			return Value{}, fmt.Errorf("binary data %q: %v", data, err)
		}
		parts := make([]string, len(b))
		for i, x := range b {
			parts[i] = fmt.Sprintf("%02x", x)
		}
		v.raw = "hex:" + strings.Join(parts, ",")
	default:
		return Value{}, fmt.Errorf("registry type %q (use sz, dword, binary)", typ)
	}
	return v, nil
}

// Line is the value as it appears in a REGEDIT4 file: "Name"=data.
func (v Value) Line() string {
	name := "@"
	if v.Name != "" && v.Name != "@" {
		name = quote(v.Name)
	}
	return name + "=" + v.raw
}

func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// Header is the first line of every REGEDIT4 file.
const Header = "REGEDIT4\r\n"

// RenderREG produces a REGEDIT4 file (CRLF), grouping values by key in first-seen order.
func RenderREG(vals []Value) []byte {
	var keys []string
	byKey := map[string][]Value{}
	for _, v := range vals {
		k := v.Root + `\` + v.Key
		if _, ok := byKey[k]; !ok {
			keys = append(keys, k)
		}
		byKey[k] = append(byKey[k], v)
	}
	var b bytes.Buffer
	b.WriteString(Header)
	for _, k := range keys {
		fmt.Fprintf(&b, "\r\n[%s]\r\n", k)
		for _, v := range byKey[k] {
			name := "@"
			if v.Name != "" && v.Name != "@" {
				name = quote(v.Name)
			}
			fmt.Fprintf(&b, "%s=%s\r\n", name, v.raw)
		}
	}
	b.WriteString("\r\n")
	return b.Bytes()
}

type Delete struct {
	Root, Key, Name string // empty Name = delete the whole key
}

func NewDelete(path, name string) (Delete, error) {
	root, key, err := SplitRoot(path)
	return Delete{root, key, name}, err
}

func infQuote(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

// RenderINF produces a setupx INF whose DefaultInstall deletes the given keys/values.
func RenderINF(dels []Delete) []byte {
	var b bytes.Buffer
	b.WriteString("; Generated by w9xm. Applied once at first boot via RunOnce.\r\n")
	b.WriteString("[Version]\r\nSignature=\"$CHICAGO$\"\r\n\r\n")
	b.WriteString("[DefaultInstall]\r\nDelReg=W9XM.DelReg\r\n\r\n[W9XM.DelReg]\r\n")
	for _, d := range dels {
		if d.Name == "" {
			fmt.Fprintf(&b, "%s,%s\r\n", shortRoots[d.Root], infQuote(d.Key))
		} else {
			fmt.Fprintf(&b, "%s,%s,%s\r\n", shortRoots[d.Root], infQuote(d.Key), infQuote(d.Name))
		}
	}
	return b.Bytes()
}
