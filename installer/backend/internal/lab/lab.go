// Guest -> host progress markers, written to COM1 by batch files.
const (
	markDOS   = "W9XM:DOS"
	markSetup = "W9XM:SETUP"
	markReady = "W9XM:READY"
	markDone  = "W9XM:DONE"
)

var keyRe = regexp.MustCompile(`(?:^|[^A-Z0-9])([A-Z0-9]{5}(?:-[A-Z0-9]{5}){4})(?:[^A-Z0-9]|$)`)

// ReadProductKey reads the user's key from a local, git-ignored file. Plain
// text or RTF (TextEdit's default) both work: the single key-shaped string
// XXXXX-XXXXX-XXXXX-XXXXX-XXXXX in the file is used.
func ReadProductKey(path string) (string, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("product key: %w (put your 98 SE key in %s)", err, path)
	}
	ms := keyRe.FindAllStringSubmatch(strings.ToUpper(string(b)), -1)
	switch len(ms) {
	case 1:
		return ms[0][1], nil
	case 0:
		return "", fmt.Errorf("no XXXXX-XXXXX-XXXXX-XXXXX-XXXXX product key found in %s", path)
	}
	return "", fmt.Errorf("%s contains %d key-shaped strings; keep only one", path, len(ms))
}

func crlf(lines ...string) []byte { return []byte(strings.Join(lines, "\r\n") + "\r\n") }

// Answers are the personal settings Setup records.
type Answers struct {
	Name, Org, Computer, Workgroup string
	TimeZone                       string // Setup's names: "Pacific", "Eastern", "GMT", "W. Europe", ...
}

// LabAnswers are used for test installs.
var LabAnswers = Answers{Name: "Win9x-Modern", Org: "Win9x-Modern Lab", Computer: "W98LAB", Workgroup: "LAB", TimeZone: "Pacific"}

func quoteINF(s string) string { return strings.ReplaceAll(s, `"`, "'") }

// msbatch is the unattended-setup answer file. Networking is left out so no
// logon prompt blocks the first boot; READY.BAT runs at every startup.
func msbatch(key string, a Answers) []byte {
	if a.Workgroup == "" {
		a.Workgroup = "WORKGROUP"
	}
	if a.TimeZone == "" {
		a.TimeZone = "GMT"
	}
	return crlf(
		"; Generated by 98Reborn: unattended Windows 98 SE setup.",
		"[BatchSetup]", "Version=3.0 (32-bit)", "",
		"[Version]", `Signature="$CHICAGO$"`, "AdvancedINF=2.5", "",
		"[Setup]",
		"Express=1", `InstallDir="C:\WINDOWS"`, "InstallType=1",
		`ProductKey="`+key+`"`,
		"EBD=0", "ShowEula=0", "ChangeDir=0", "OptionalComponents=1",
		"System=0", "CCP=0", "CleanBoot=0", "Display=0", "DevicePath=0",
		"NoDirWarn=1", `TimeZone="`+quoteINF(a.TimeZone)+`"`, "Uninstall=0", "VRC=0", "NoPrompt2Boot=1", "",
		"[NameAndOrg]", `Name="`+quoteINF(a.Name)+`"`, `Org="`+quoteINF(a.Org)+`"`, "Display=0", "",
		"[Network]", `ComputerName="`+quoteINF(a.Computer)+`"`, `Workgroup="`+quoteINF(a.Workgroup)+`"`, `Description="98Reborn"`,
		"Display=0", "Clients=", "Protocols=", "Services=",
		"IgnoreDetectedNetCards=1", "ValidateNetCardResources=0", "",
		"[Install]", "AddReg=W9XM.AddReg", "",
		"[W9XM.AddReg]",
		`HKLM,"Software\Microsoft\Windows\CurrentVersion\Run","W9XMReady",,"C:\W9XM\READY.BAT"`,
	)
}

var readyBat = crlf(
	"@ECHO OFF",
	"ECHO "+markReady+" > COM1",
	`IF EXIST C:\W9XM\CHECK.BAT CALL C:\W9XM\CHECK.BAT`,
	"ECHO "+markDone+" > COM1",
	`C:\WINDOWS\RUNDLL32.EXE USER.EXE,ExitWindows`,
)

func floppyConfig() []byte {
	return crlf("DEVICE=HIMEM.SYS /TESTMEM:OFF", "DOS=HIGH", "FILES=60", "BUFFERS=30", "LASTDRIVE=Z")
}

func floppyAutoexec(setupDir string, acpi bool) []byte {
	sw := ""
	if acpi {
		sw = " /p j" // install in ACPI mode
	}
	return crlf(
		"@ECHO OFF",
		"ECHO "+markDOS+" > COM1",
		"FDISK /MBR",
		`C:\`+setupDir+`\SMARTDRV.EXE`,
		"C:",
		`CD \`+setupDir,
		"ECHO "+markSetup+" > COM1",
		`SETUP.EXE C:\MSBATCH.INF /IS /IE /IM /IV`+sw,
	)
}

// Source supplies the Windows 98 SE setup folder and the CD's boot floppy:
// the user's CD image (lab) or the 98SE folder on the installer medium.
type Source interface {
	SetupDirName() string // "WIN98"
	CopySetup(v *fat.FS, dst string) (int64, error)
	BootFloppy() ([]byte, error)
}

type isoSource struct{ m *media.Media }

// ISOSource reads from an opened Windows 98 SE CD image.
func ISOSource(m *media.Media) Source { return isoSource{m} }

func (s isoSource) SetupDirName() string { return strings.ToUpper(s.m.SetupDir) }
func (s isoSource) BootFloppy() ([]byte, error) {
	b, _, err := s.m.ISO.ReadBootImage()
	return b, err
}
func (s isoSource) CopySetup(v *fat.FS, dst string) (int64, error) {
	return copyTree(s.m.ISO, v, s.m.SetupDir, dst)
}

// DirSource reads the setup files from a folder (the installer medium's 98SE)
// and the boot floppy from a file saved next to it by the 98Reborn Tool.
type DirSource struct{ Dir, Floppy string }

func (s DirSource) SetupDirName() string        { return "WIN98" }
func (s DirSource) BootFloppy() ([]byte, error) { return os.ReadFile(s.Floppy) }
func (s DirSource) CopySetup(v *fat.FS, dst string) (int64, error) {
	return copyDir(s.Dir, v, dst)
}

func copyDir(src string, v *fat.FS, dst string) (int64, error) {
	if err := v.MkdirAll(dst); err != nil {
		return 0, err
	}
	ents, err := os.ReadDir(src)
	if err != nil {
		return 0, err
	}
	var total int64
	for _, e := range ents {
		name := strings.ToUpper(e.Name())
		if e.IsDir() {
			n, err := copyDir(filepath.Join(src, e.Name()), v, dst+"/"+name)
			total += n
			if err != nil {
				return total, err
			}
			continue
		}
		b, err := os.ReadFile(filepath.Join(src, e.Name()))
		if err != nil {
			return total, err
		}
		fi, _ := e.Info()
		if err := v.WriteFile(dst+"/"+name, b, fi.ModTime()); err != nil {
			return total, fmt.Errorf("%s: %w", e.Name(), err)
		}
		total += int64(len(b))
	}
	return total, nil
}

// copyTree copies a CD directory onto the FAT volume.
func copyTree(im *iso9660.Image, v *fat.FS, src, dst string) (int64, error) {
	if err := v.MkdirAll(dst); err != nil {
		return 0, err
	}
	ents, err := im.ReadDir(src)
	if err != nil {
		return 0, err
	}
	var total int64
	for _, e := range ents {
		name := strings.ToUpper(e.Name)
		if e.IsDir {
			n, err := copyTree(im, v, e.Path, dst+"/"+name)
			total += n
			if err != nil {
				return total, err
			}
			continue
		}
		b, err := im.ReadFile(e.Path)
		if err != nil {
			return total, err
		}
		if err := v.WriteFile(dst+"/"+name, b, e.ModTime); err != nil {
			return total, fmt.Errorf("%s: %w", e.Path, err)
		}
		total += int64(len(b))
	}
	return total, nil
}

type InstallOptions struct {
	ISO, ProductKey, Out, QEMU string
	DiskMB                     int
	Show                       bool
	Timeout                    time.Duration
	// Resume continues an interrupted install on the existing
	// golden.img.partial instead of building a new disk.
	Resume bool
	// AcceptEULA lets the harness select "I accept" on Setup's license page on
	// the user's behalf. Without it, the run waits for the user to accept in
	// the --show window.
	AcceptEULA bool
}

// wizard answers the pages 98 SE Setup still shows after its first reboot,
// even with MSBATCH.INF's Display=0 / ShowEula=0. Pages are recognized by
// their heading (see headingPrint); when one of them sits idle, its keys are
// sent. Unrecognized screens are left alone.
type wizardPage struct {
	name   string
	chords [][]string
	eula   bool // needs --accept-eula
	key    bool // the product key page: staying here means the key was rejected
}

type wizard struct {
	acceptEULA bool
	pages      map[uint64]wizardPage
	tries      map[uint64]int
	told       bool
	err        error // Setup can't continue (e.g. the product key was rejected)
}

func newWizard(acceptEULA bool) *wizard {
	return &wizard{acceptEULA: acceptEULA, tries: map[uint64]int{}, pages: map[uint64]wizardPage{
		0x1c878c850d051ad0: {name: "User Information: Next", chords: [][]string{{"ret"}}},
		0x891d70af46693a4f: {name: "License Agreement: I accept (--accept-eula), Next", chords: [][]string{{"alt", "a"}, {"ret"}}, eula: true},
		0x94f5cb29cba0aa1b: {name: "Product Key: Next (pre-filled from MSBATCH.INF)", chords: [][]string{{"ret"}}, key: true},
		0x1b691dd75e8f9f88: {name: "Start Wizard: Finish", chords: [][]string{{"ret"}}},
	}}
}

// act handles an idle screen; it returns a log line ("" for none).
func (w *wizard) act(vm *VM, img image.Image) string {
	fp := headingPrint(img)
	pg, ok := w.pages[fp]
	if !ok {
		return ""
	}
	if pg.eula && !w.acceptEULA {
		if w.told {
			return ""
		}
		w.told = true
		return "Setup is waiting on the License Agreement: accept it in the window (--show), or rerun with --accept-eula"
	}
	if w.tries[fp] >= 3 {
		if pg.key && w.err == nil {
			w.err = errors.New("Windows Setup didn't accept the product key. Check the key on your Windows 98 SE certificate and try again")
		}
		return ""
	}
	w.tries[fp]++
	for _, chord := range pg.chords {
		vm.SendKeys(chord...)
		time.Sleep(time.Second)
	}
	return pg.name
}

// Install builds a disk + boot floppy, runs unattended Setup in QEMU, and
// leaves Out/golden.img: a clean, booted 98 SE install for module tests.
func Install(o InstallOptions, log io.Writer) error {
	if o.DiskMB == 0 {
		o.DiskMB = 2048
	}
	m, err := media.Open(o.ISO)
	if err != nil {
		return err
	}
	defer m.Close()
	if m.Product != media.Win98SE {
		return fmt.Errorf("%s is %s; the lab installs Windows 98 Second Edition", o.ISO, m.Product)
	}
	if !o.Resume {
		fmt.Fprintf(log, "Building %d MB disk with the setup files from %s...\n", o.DiskMB, filepath.Base(o.ISO))
	}
	err = RunSetup(SetupOptions{
		Source: ISOSource(m), Image: filepath.Join(o.Out, "golden.img.partial"), DiskBytes: int64(o.DiskMB) << 20,
		Key: o.ProductKey, Answers: LabAnswers, AcceptEULA: o.AcceptEULA, QEMU: o.QEMU, Show: o.Show,
		WorkDir: o.Out, Timeout: o.Timeout, Log: log, Resume: o.Resume,
	})
	if err != nil {
		return err
	}
	return Finalize(o.Out, m)
}

// SetupOptions describe one unattended Windows 98 SE Setup run in a VM.
type SetupOptions struct {
	Source Source
	Image  string // disk image to create (sparse)
	// Partition placement. Zero PartSectors means one partition filling a
	// DiskBytes image (the lab). The installer passes the exact start and
	// size of the real partition, so the result can be copied there 1:1.
	PartStart, PartSectors int64
	DiskBytes              int64
	Key                    string
	Answers                Answers
	AcceptEULA             bool
	QEMU                   string
	Show                   bool
	WorkDir                string // floppy image, screenshots and logs (WorkDir/install)
	Timeout                time.Duration
	Log                    io.Writer
	Resume                 bool
	// ACPI installs Windows 98 in ACPI mode (Setup /p j): right for PCs
	// started through ReBIOS, which gives Windows 98 ACPI tables it
	// understands. Native CSM firmware's tables are for modern Windows, so
	// those PCs get the non-ACPI (Plug and Play BIOS) install.
	ACPI bool
}

// RunSetup builds the setup disk and boot floppy, runs Setup until Windows
// reaches the desktop, and shuts the VM down.
func RunSetup(o SetupOptions) error {
	if o.Timeout == 0 {
		o.Timeout = 3 * time.Hour
	}
	log := o.Log
	if log == nil {
		log = io.Discard
	}
	qemu, err := FindQEMU(o.QEMU)
	if err != nil {
		return err
	}
	runDir := filepath.Join(o.WorkDir, "install")
	if err := os.MkdirAll(runDir, 0o755); err != nil {
		return err
	}
	floppy := filepath.Join(o.WorkDir, "bootfloppy.img")
	cfg := VMConfig{QEMU: qemu, Disk: o.Image, Floppy: floppy, BootFloppy: true, Show: o.Show, LogDir: runDir}
	if o.Resume {
		if _, err := os.Stat(o.Image); err != nil {
			return fmt.Errorf("nothing to resume: %w", err)
		}
		fmt.Fprintln(log, "Resuming the install on the existing disk...")
		cfg.Floppy, cfg.BootFloppy = "", false
	} else {
		start, n, size := o.PartStart, o.PartSectors, o.DiskBytes
		if n == 0 {
			start, n = 63, size/512-63
		} else {
			size = (start + n) * 512
		}
		if err := buildInstallDisk(o.Source, o.Image, start, n, size, o.Key, o.Answers); err != nil {
			return err
		}
		if err := buildFloppy(o.Source, floppy, o.ACPI); err != nil {
			return err
		}
	}

	fmt.Fprintf(log, "Starting QEMU (screenshots: %s/screen.png)...\n", runDir)
	vm, err := StartVM(cfg)
	if err != nil {
		return err
	}
	wiz := newWizard(o.AcceptEULA)
	if o.Resume {
		wiz = nil // the wizard pages were already answered before the interruption
	}
	if err := watch(vm, runDir, o.Timeout, log, wiz); err != nil {
		return err
	}
	fmt.Fprintln(log, "Setup finished and Windows reached the desktop. Shutting down...")
	finish(vm, log)
	return nil
}

// Finalize turns a finished golden.img.partial into golden.img (also usable to
// recover a run whose harness was interrupted after the guest reported DONE).
func Finalize(out string, m *media.Media) error {
	tmp := filepath.Join(out, "golden.img.partial")
	// Lab tweak: no ScanDisk prompt after a forced power-off.
	if err := withImage(tmp, func(v *fat.FS) error { return setMSDOSSys(v, "AutoScan", "0") }); err != nil {
		return err
	}
	st, _ := os.Stat(tmp)
	info, _ := json.MarshalIndent(map[string]any{
		"product": m.Product, "setup_sha256": m.SetupSHA256, "disk_mb": st.Size() >> 20,
		"created": time.Now().UTC().Format(time.RFC3339),
	}, "", "  ")
	os.WriteFile(filepath.Join(out, "golden.json"), info, 0o644)
	return os.Rename(tmp, filepath.Join(out, "golden.img"))
}

func buildInstallDisk(src Source, imgPath string, start, n, size int64, key string, a Answers) error {
	fh, err := os.Create(imgPath)
	if err != nil {
		return err
	}
	defer fh.Close()
	if err := fh.Truncate(size); err != nil {
		return err
	}
	if err := fat.WriteMBR(fh, []fat.Partition{{Bootable: true, Type: 0x0C, StartLBA: uint32(start), Sectors: uint32(n)}}); err != nil {
		return err
	}
	if err := fat.Format32(fh, start*512, n*512, "WIN98SE"); err != nil {
		return err
	}
	v, err := fat.Open(fh, start*512)
	if err != nil {
		return err
	}
	if _, err := src.CopySetup(v, src.SetupDirName()); err != nil {
		return err
	}
	for p, b := range map[string][]byte{"MSBATCH.INF": msbatch(key, a), "W9XM/READY.BAT": readyBat} {
		if err := v.MkdirAll(path.Dir(p)); err != nil {
			return err
		}
		if err := v.WriteFile(p, b, time.Time{}); err != nil {
			return err
		}
	}
	return v.Sync()
}

func buildFloppy(src Source, path string, acpi bool) error {
	img, err := src.BootFloppy()
	if err != nil {
		return err
	}
	if err := os.WriteFile(path, img, 0o644); err != nil {
		return err
	}
	return withImage(path, func(v *fat.FS) error {
		// JO.SYS shows the CD's "Boot from Hard Disk / CD-ROM" menu (default:
		// hard disk). Without it the boot sector loads IO.SYS (DOS) directly.
		if err := v.Remove("JO.SYS"); err != nil && !engine.IsNotExist(err) {
			return err
		}
		if err := v.WriteFile("CONFIG.SYS", floppyConfig(), time.Time{}); err != nil {
			return err
		}
		return v.WriteFile("AUTOEXEC.BAT", floppyAutoexec(src.SetupDirName(), acpi), time.Time{})
	})
}

// RemoveLabHooks deletes the setup-time helpers from a finished install
// (C:\W9XM, C:\MSBATCH.INF with the product key). The Run entry that pointed
// at READY.BAT is removed by the installer's cleanup module.
func RemoveLabHooks(v *fat.FS) error {
	for _, p := range []string{"W9XM/READY.BAT", "W9XM/CHECK.BAT", "MSBATCH.INF"} {
		if err := v.Remove(p); err != nil && !engine.IsNotExist(err) {
			return err
		}
	}
	if ents, err := v.ReadDir("W9XM"); err == nil && len(ents) == 0 {
		v.Remove("W9XM")
	}
	return v.Sync()
}

func withImage(path string, fn func(*fat.FS) error) error {
	fh, err := os.OpenFile(path, os.O_RDWR, 0)
	if err != nil {
		return err
	}
	defer fh.Close()
	v, err := fat.OpenImage(fh)
	if err != nil {
		return err
	}
	if err := fn(v); err != nil {
		return err
	}
	if err := v.Sync(); err != nil {
		return err
	}
	return fh.Sync()
}

func setMSDOSSys(v *fat.FS, key, val string) error {
	b, err := v.ReadFile("MSDOS.SYS")
	if err != nil {
		return err
	}
	f := ini.Parse(b)
	if f.Set("Options", key, val) {
		return v.WriteFile("MSDOS.SYS", f.Bytes(), time.Time{})
	}
	return nil
}

// watch follows the serial markers and keeps a fresh screenshot until DONE.
// With a wizard, a screen that stays unchanged triggers the next wizard step.
func watch(vm *VM, dir string, timeout time.Duration, log io.Writer, wiz *wizard) error {
	deadline := time.Now().Add(timeout)
	seen := map[string]bool{}
	start := time.Now()
	lastShot := time.Time{}
	shots := 0
	var lastImg image.Image
	var lastProbe, stillSince time.Time
	const stallAfter = 30 * time.Second
	for {
		if wiz != nil && seen[markSetup] && time.Since(lastProbe) > 15*time.Second {
			lastProbe = time.Now()
			probe := filepath.Join(dir, ".probe.png")
			var img image.Image
			err := vm.Screenshot(probe)
			if err == nil {
				img, err = readPNG(probe)
			}
			if err == nil {
				if lastImg == nil || pixelDiff(lastImg, img) > idlePixels {
					lastImg, stillSince = img, time.Now()
				} else if time.Since(stillSince) > stallAfter {
					if msg := wiz.act(vm, img); msg != "" {
						fmt.Fprintf(log, "[%s] wizard: %s\n", time.Since(start).Round(time.Second), msg)
					}
					if wiz.err != nil {
						vm.Screenshot(filepath.Join(dir, "screen.png"))
						vm.Kill()
						return wiz.err
					}
					stillSince = time.Now()
				}
			}
		}
		serial := vm.Serial()
		for _, mk := range []string{markDOS, markSetup, markReady, markDone} {
			if !seen[mk] && strings.Contains(serial, mk) {
				seen[mk] = true
				fmt.Fprintf(log, "[%s] guest: %s\n", time.Since(start).Round(time.Second), mk)
			}
		}
		if seen[markDone] {
			vm.Screenshot(filepath.Join(dir, "screen.png"))
			return nil
		}
		select {
		case <-vm.Exited():
			return fmt.Errorf("QEMU exited before the guest reported %s (see %s)", markDone, dir)
		default:
		}
		if time.Since(lastShot) > 30*time.Second {
			vm.Screenshot(filepath.Join(dir, "screen.png"))
			if shots%10 == 0 {
				vm.Screenshot(filepath.Join(dir, fmt.Sprintf("screen-%03d.png", shots/10)))
			}
			shots++
			lastShot = time.Now()
		}
		if time.Now().After(deadline) {
			vm.Screenshot(filepath.Join(dir, "screen.png"))
			vm.Kill()
			return fmt.Errorf("timed out after %v waiting for the guest (last screen: %s/screen.png)", timeout, dir)
		}
		time.Sleep(2 * time.Second)
	}
}

// idlePixels: changes smaller than this (a blinking caret, the mouse
// pointer) don't count as the screen changing.
const idlePixels = 300

func readPNG(path string) (image.Image, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return png.Decode(f)
}

// pixelDiff counts differing pixels (screens of different size differ completely).
func pixelDiff(a, b image.Image) int {
	ab, bb := a.Bounds(), b.Bounds()
	if ab != bb {
		return ab.Dx() * ab.Dy()
	}
	n := 0
	for y := ab.Min.Y; y < ab.Max.Y; y++ {
		for x := ab.Min.X; x < ab.Max.X; x++ {
			r1, g1, b1, _ := a.At(x, y).RGBA()
			r2, g2, b2, _ := b.At(x, y).RGBA()
			if r1 != r2 || g1 != g2 || b1 != b2 {
				n++
			}
		}
	}
	return n
}

// finish waits for the guest's own shutdown, then forces power-off.
func finish(vm *VM, log io.Writer) {
	select {
	case <-vm.Exited():
		return
	case <-time.After(3 * time.Minute):
	}
	fmt.Fprintln(log, "Guest did not power off by itself; sending ACPI power-off.")
	vm.Shutdown(90 * time.Second)
}

// sparseCopy copies a disk image, leaving zero runs as holes.
func sparseCopy(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	st, err := in.Stat()
	if err != nil {
		return err
	}
	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	defer out.Close()
	if err := out.Truncate(st.Size()); err != nil {
		return err
	}
	buf := make([]byte, 1<<20)
	for off := int64(0); off < st.Size(); {
		n, err := in.ReadAt(buf, off)
		if n > 0 && !allZero(buf[:n]) {
			if _, werr := out.WriteAt(buf[:n], off); werr != nil {
				return werr
			}
		}
		off += int64(n)
		if err == io.EOF {
			break
		}
		if err != nil {
			return err
		}
	}
	return out.Sync()
}

func allZero(b []byte) bool {
	for _, c := range b {
		if c != 0 {
			return false
		}
	}
	return true
}

type TestOptions struct {
	Golden, Out, QEMU string
	Modules           []*module.Module
	Params            map[string]map[string]string
	Facts             *module.Facts
	Media             map[string]engine.MediaSource
	Show              bool
	Timeout           time.Duration
}

type Check struct {
	What string
	OK   bool
	Info string
}

type TestResult struct {
	RunDir string
	Plan   *engine.Plan
	Checks []Check
}

func (r *TestResult) Passed() bool {
	for _, c := range r.Checks {
		if !c.OK {
			return false
		}
	}
	return len(r.Checks) > 0
}

// Test applies modules to a copy of the golden image, boots it, and checks
// inside the guest that Windows starts and registry changes were imported.
func Test(o TestOptions, log io.Writer) (*TestResult, error) {
	if o.Timeout == 0 {
		o.Timeout = 45 * time.Minute
	}
	qemu, err := FindQEMU(o.QEMU)
	if err != nil {
		return nil, err
	}
	runDir := filepath.Join(o.Out, "runs", time.Now().Format("20060102-150405"))
	if err := os.MkdirAll(runDir, 0o755); err != nil {
		return nil, err
	}
	disk := filepath.Join(runDir, "disk.img")
	fmt.Fprintf(log, "Copying golden image to %s...\n", runDir)
	if err := sparseCopy(o.Golden, disk); err != nil {
		return nil, err
	}
	res := &TestResult{RunDir: runDir}

	tgt, err := engine.OpenImageTarget(disk)
	if err != nil {
		return nil, err
	}
	plan, err := engine.NewPlan(engine.Options{Target: tgt, Facts: o.Facts, Params: o.Params, Media: o.Media, Tool: "w9xm lab"}, o.Modules)
	if err != nil {
		tgt.Close()
		return nil, err
	}
	res.Plan = plan
	if _, err := plan.Apply(); err != nil {
		tgt.Close()
		return nil, err
	}
	fmt.Fprintf(log, "Applied %d modules (%d file changes).\n", len(plan.Modules), len(plan.Changes))

	// Have the guest export every key we set, so we can compare after boot.
	type expect struct {
		file, key, line string
		absent          bool // a value or key the plan deletes
	}
	var exps []expect
	var check []string
	keyFile := map[string]string{}
	exportFile := func(k string) string {
		f, ok := keyFile[strings.ToUpper(k)]
		if !ok {
			f = fmt.Sprintf("K%03d.REG", len(keyFile)+1)
			keyFile[strings.ToUpper(k)] = f
			check = append(check, fmt.Sprintf(`START /W C:\WINDOWS\REGEDIT.EXE /E C:\W9XM\CHECK\%s "%s"`, f, k))
		}
		return f
	}
	dels := plan.RegistryDeletes()
	deleted := func(root, key, name string) bool {
		for _, d := range dels {
			if !strings.EqualFold(d.Root, root) {
				continue
			}
			if d.Name == "" && (strings.EqualFold(d.Key, key) || strings.HasPrefix(strings.ToUpper(key), strings.ToUpper(d.Key)+`\`)) {
				return true
			}
			if strings.EqualFold(d.Key, key) && strings.EqualFold(d.Name, name) {
				return true
			}
		}
		return false
	}
	for _, v := range plan.Registry() {
		k := v.Root + `\` + v.Key
		if strings.Contains(strings.ToUpper(k), `\RUNONCE`) || deleted(v.Root, v.Key, v.Name) {
			continue // consumed at first boot, or deleted later by the same plan
		}
		exps = append(exps, expect{file: exportFile(k), key: k, line: v.Line()})
	}
	for _, d := range dels {
		k := d.Root + `\` + d.Key
		exps = append(exps, expect{file: exportFile(k), key: k, line: d.Name, absent: true})
	}
	for _, d := range []string{"W9XM/CHECK"} {
		if names, err := tgt.ReadDir(d); err == nil {
			for _, n := range names {
				tgt.Remove(d + "/" + n)
			}
		} else if err := tgt.Mkdir(d); err != nil {
			tgt.Close()
			return nil, err
		}
	}
	if err := tgt.WriteFile("W9XM/CHECK.BAT", crlf(append([]string{"@ECHO OFF"}, check...)...), 0o644); err != nil {
		tgt.Close()
		return nil, err
	}
	if err := tgt.Close(); err != nil {
		return nil, err
	}

	fmt.Fprintln(log, "Booting the patched image...")
	vm, err := StartVM(VMConfig{QEMU: qemu, Disk: disk, Show: o.Show, LogDir: runDir})
	if err != nil {
		return nil, err
	}
	werr := watch(vm, runDir, o.Timeout, log, nil)
	booted := werr == nil
	res.Checks = append(res.Checks, Check{"Windows boots to the desktop with the modules applied", booted, errString(werr)})
	if !booted {
		return res, nil
	}
	finish(vm, log)

	tgt, err = engine.OpenImageTarget(disk)
	if err != nil {
		return res, err
	}
	defer tgt.Close()
	if len(plan.Registry()) > 0 {
		_, pendErr := tgt.Stat("W9XM/PENDING.REG")
		_, applErr := tgt.Stat("W9XM/APPLIED.REG")
		res.Checks = append(res.Checks, Check{"Real-mode REGEDIT imported PENDING.REG at boot (renamed to APPLIED.REG)",
			engine.IsNotExist(pendErr) && applErr == nil, ""})
	}
	exports := map[string]string{}
	for _, e := range exps {
		if _, ok := exports[e.file]; !ok {
			b, err := tgt.ReadFile("W9XM/CHECK/" + e.file)
			if err != nil {
				exports[e.file] = ""
			} else {
				exports[e.file] = string(b)
			}
		}
		if e.absent {
			ok := !regHasValue(exports[e.file], e.key, e.line)
			what := fmt.Sprintf("Registry value %s %q deleted at first boot", e.key, e.line)
			if e.line == "" {
				what = fmt.Sprintf("Registry key %s deleted at first boot", e.key)
			}
			info := ""
			if !ok {
				info = "still present in the guest's REGEDIT /E export"
			}
			res.Checks = append(res.Checks, Check{what, ok, info})
			continue
		}
		ok := regHasLine(exports[e.file], e.key, e.line)
		info := ""
		if !ok {
			info = "not found in the guest's REGEDIT /E export"
			if exports[e.file] == "" {
				info = "export missing: " + e.file
			}
		}
		res.Checks = append(res.Checks, Check{fmt.Sprintf("Registry %s %s", e.key, e.line), ok, info})
	}
	for _, c := range plan.Changes {
		if c.Kind == "delete" || strings.HasPrefix(strings.ToUpper(c.Path), "W9XM/") {
			continue
		}
		got, err := tgt.ReadFile(c.Path)
		ok := err == nil && bytes.Equal(got, c.New)
		info := ""
		if !ok {
			info = "Windows changed or removed it during boot"
		}
		res.Checks = append(res.Checks, Check{"File survives a boot unchanged: " + c.Path, ok, info})
	}
	return res, nil
}

func errString(err error) string {
	if err == nil {
		return ""
	}
	return err.Error()
}

// regHasLine reports whether a REGEDIT4 export contains line under key.
func regHasLine(export, key, line string) bool {
	d := textfile.Parse([]byte(export))
	in := false
	name, val, _ := strings.Cut(line, "=")
	for _, l := range d.Lines {
		t := strings.TrimSpace(l)
		if strings.HasPrefix(t, "[") {
			in = strings.EqualFold(strings.Trim(t, "[]"), key)
			continue
		}
		if !in {
			continue
		}
		n, v, ok := strings.Cut(t, "=")
		if ok && strings.EqualFold(n, name) && strings.EqualFold(v, val) {
			return true
		}
	}
	return false
}

// regHasValue reports whether key exists in a REGEDIT4 export and, when name is
// non-empty, whether it has a value with that name ("" checks the key itself).
func regHasValue(export, key, name string) bool {
	d := textfile.Parse([]byte(export))
	in := false
	for _, l := range d.Lines {
		t := strings.TrimSpace(l)
		if strings.HasPrefix(t, "[") {
			in = strings.EqualFold(strings.Trim(t, "[]"), key)
			if in && name == "" {
				return true
			}
			continue
		}
		if in {
			n, _, ok := strings.Cut(t, "=")
			if ok && strings.EqualFold(strings.Trim(n, `"`), name) {
				return true
			}
		}
	}
	return false
}

